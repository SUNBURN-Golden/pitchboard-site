import assert from 'node:assert/strict';
import w, { sign, verify } from '../worker/_worker.js';
const S='test-secret';
const t=await sign(S,{sub:'1',exp:Math.floor(Date.now()/1000)+60});
assert.deepEqual((await verify(S,t)).sub,'1');
assert.equal(await verify('other',t),null);
assert.equal(await verify(S,t.slice(0,-2)+'xx'),null);
assert.equal(await verify(S,await sign(S,{exp:1})),null);
const env={DB:{},GOOGLE_CLIENT_ID:'cid',GOOGLE_CLIENT_SECRET:'x',SESSION_SECRET:S,ASSETS:{fetch:()=>new Response('asset')}};
const O='https://pitchboard.soulbound.co.kr';
let r=await w.fetch(new Request(O+'/api/auth/google'),env);
assert.equal(r.status,302); const loc=new URL(r.headers.get('Location'));
assert.equal(loc.host,'accounts.google.com'); assert.equal(loc.searchParams.get('redirect_uri'),O+'/api/auth/callback');
const st=r.headers.get('Set-Cookie').split(';')[0].split('=')[1];
assert.equal((await verify(S,st)).nl,1);
r=await w.fetch(new Request(O+'/api/auth/google?newsletter=0'),env);
assert.equal((await verify(S,r.headers.get('Set-Cookie').split(';')[0].split('=')[1])).nl,0);
r=await w.fetch(new Request(O+'/api/auth/callback?code=c&state=bad',{headers:{Cookie:'pb_oauth='+st}}),env);
assert.equal(r.status,302); assert.match(r.headers.get('Location'),/error=state/);
assert.equal((await w.fetch(new Request(O+'/api/me'),env)).status,401);
assert.equal((await w.fetch(new Request(O+'/api/auth/google'),{ASSETS:env.ASSETS})).status,503);
assert.equal((await w.fetch(new Request(O+'/api/nope'),env)).status,404);
assert.equal(await (await w.fetch(new Request(O+'/'),env)).text(),'asset');
r=await w.fetch(new Request(O+'/api/auth/logout',{method:'POST'}),env); assert.match(r.headers.get('Set-Cookie'),/Max-Age=0/);
console.log('worker tests ok');
